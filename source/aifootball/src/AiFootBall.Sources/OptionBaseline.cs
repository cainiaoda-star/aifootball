/// <summary>
/// 任意玩法任意档位的实测概率基线（%，2026-11-08 建）。
///
/// 为什么需要它：<see cref="LeagueHalfFullBaseline"/> 只覆盖半全场六个反转档，
/// 于是榜面上**只有单列注带着 BaselineProbability**，主榜注全是 NULL。
/// 后果是 <see cref="MilkPick.Ev"/> 变成了纯模型自证——用户在页面上看到「EV 1.24」，
/// 那只是「模型概率 × 赔率」，没有任何联赛实测校准，而每个玩法的返奖率
/// （半全场/总进球 0.797、比分 0.710）早把上限写死了。用户按 EV 挑注，
/// 正好挑到模型高估最狠的那一注（2026-11-08 十注复盘：八注真实 EV 加权 0.80 ≈ 返奖率）。
///
/// 覆盖范围与口径（全部 2023-08 起，FbMatch 完赛场次）：
///   · 半全场九档：反转六档走 <see cref="LeagueHalfFullBaseline"/>（联赛分层），
///     顺风三档（胜胜/平平/负负）走本类的 <see cref="BqForward"/>（联赛分层，样本 ≥600）。
///   · 比分 31 档：全库口径，**不分联赛**。31 档 × 几十个联赛的交叉表既没人维护也用不上——
///     比分档位的联赛差异主要在「大小球倾向」，而这一层已经由赔率本身表达了。
///   · 总进球 8 档：全库口径，同上。
///
/// 数据凭证：dbo.FbMatch 全库聚合（269091 场）。刷新方法见各类注释，不要手改单个数字。
///
/// <para>
/// **已知局限（2026-11-08 当天实测，必须知道）**：本类全部是**边际平均**——
/// 「这一档在所有场次里的频率」，**没有条件化到赔率**。同一档在不同赔率位置的真实频率差别极大。
/// 以半全场负负为例（主流联赛 1445 场，欧赔口径按客胜赔率分档）：
/// 客胜 &lt;2.20 → 45.88% / 2.20-2.60 → 32.57% / 2.60-3.00 → 21.16% / 3.00-3.40 → 14.37% / ≥3.40 → 11.79%。
/// 全库均值 18.2% 落在这条曲线的中段，于是**对强势客队偏保守、对均势/弱客队偏乐观**。
/// 实例：江原FC vs 全北现代（竞彩客胜 2.74 ≈ 欧赔 3.05），联赛均值给 17.37%、
/// 条件化后只有 14.4%，@5.30 的 EV 从 0.921 掉到 0.77——差 16 个点，足以改变"下不下"的结论。
/// 同一个错误此前在比分 0:0 上犯过一次（全库 7.35% 算出 EV 1.139，而市场只给 6.4%）。
/// **所以本类的输出只能当下限筛子（MinBaselineEvRatio）用，不能当价值证明。**
/// 要做条件化，得按「赔率档 × 档位」重建这张表并跑 walk-forward Brier，不是改个系数的事。
/// </para>
/// </summary>
