    /// <summary>把赔率映射到分档下标（0..edges.Length）。边界含左不含右。</summary>
    public static int BandOf(decimal[] edges, decimal value)
    {
        var i = 0;
        while (i < edges.Length && value >= edges[i]) i++;
        return i;
    }

