    /// <summary>
    /// 取某联赛某玩法某档位的实测概率（百分数）。返回 null = 该档位没有基线，
    /// 调用方必须把 <see cref="MilkPick.BaselineProbability"/> 留空，**不要填 0 或猜一个值**。
    ///
    /// 三个玩法的口径不同（半全场联赛分层、比分/总进球全库），不要假设「同一个 league 参数处处生效」。
    /// </summary>
    public static decimal? Pct(string? league, string playType, string optionCode,
                               decimal? homeOdds = null, decimal? awayOdds = null)
    {
        switch (playType)
        {
            case JcPlayTypes.Bq:
                return BqPct(league, optionCode, homeOdds, awayOdds);
            case JcPlayTypes.Bf:
                return BfAll.TryGetValue(optionCode, out var bf) ? bf : null;
            case JcPlayTypes.Jq:
                // 档位编码就是「球数」，7 表示 7 球及以上。
                if (!int.TryParse(optionCode, out var g) || g < 0) return null;
                return g >= 7 ? JqAll[7] : JqAll[g];
            default:
                // 胜平负/让球不落基线：这两个玩法的市场水位最薄（返奖率 0.878），
                // 且方向已由方向闸单独处理，再叠一层「全库均值」只会制造噪声。
                return null;
        }
    }

    private static decimal? BqPct(string? league, string optionCode, decimal? homeOdds, decimal? awayOdds)
    {
        // 反转六档优先走既有分层表（含 LeagueNames 归一与已知联赛显式否决）。
        var rev = LeagueHalfFullBaseline.Pct(league, optionCode);
        if (rev is not null) return rev;

        // 顺风三档：**赔率条件化优先于联赛分层**（2026-11-08 加）。
        // 依据是两者解释力差一个量级——同一档位在赔率两端相差 4 倍（胜胜 62%→17%、负负 46%→12%），
        // 而联赛之间的差异通常不到 1.5 倍。赔率把「这支队到底多强」定价了，联赛均值没有。
        // 查询顺序：能拿到该场赔率就用条件值，拿不到（快照缺 SPF）才回退联赛分层，最后回默认值。
        if (optionCode == "3-3" && homeOdds is decimal ho1 && ho1 > 0)
            return BqWinWinByHome[BandOf(BqHomeOddsEdges, ho1 * JcToEuro)];
        if (optionCode == "1-1" && homeOdds is decimal ho2 && ho2 > 0)
            return BqDrawByHome[BandOf(BqHomeOddsEdges, ho2 * JcToEuro)];
        if (optionCode == "0-0" && awayOdds is decimal ao && ao > 0)
            return BqLoseLoseByAway[BandOf(BqAwayOddsEdges, ao * JcToEuro)];

        var i = optionCode switch
        {
            "3-3" => 0,
            "1-1" => 1,
            "0-0" => 2,
            _ => -1
        };
        if (i < 0) return null;

        var name = LeagueNames.Resolve(league);
        if (name.Length > 0 && BqForward.TryGetValue(name, out var row)) return row[i];
        return BqForwardDefault[i];
    }

