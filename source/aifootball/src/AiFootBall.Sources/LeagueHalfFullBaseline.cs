    /// <summary>118 个联赛（≥500 场）的六档均值，未知联赛用它兜底（不是拍脑袋的 1.5%）。</summary>
    private static readonly decimal[] DefaultPct = { 4.94m, 2.13m, 15.21m, 11.31m, 2.65m, 4.73m };

    /// <summary>刷新基线表的 SQL 位置提示（换赛季重跑时用）。</summary>
    public const string DumpSqlHint = "dbo.FbLeagueHalfFullBase";

    /// <summary>
    /// 取某联赛某反转档的实测概率（百分数）。联赛不在表里走 <see cref="DefaultPct"/> 兜底。
    /// 非反转档返回 null——顺风档（胜胜/平平/负负）不走分层，仍是全局 12% 门槛。
    /// </summary>
    public static decimal? Pct(string? league, string code)
    {
        var i = Array.IndexOf(ReverseCodes, code);
        if (i < 0) return null;
        // 竞彩名与数据源名不同时先对齐（韩职→K1联赛 等，见 LeagueNames）。
        // 表里的键是数据源写法，用得最多的是「K1联赛」那一行——不转换的话韩职永远走兜底均值。
        var name = LeagueNames.Resolve(league);
        if (name.Length > 0 && Table.TryGetValue(name, out var row)) return row[i];
        return DefaultPct[i];
    }

