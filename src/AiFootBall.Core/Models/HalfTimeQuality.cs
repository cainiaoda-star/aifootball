namespace AiFootBall.Core.Models;

/// <summary>
/// 半场比分可用性判据（2026-11-08 建，同一天被推翻重写了一次，教训在后面）。
///
/// ## 事故
/// <c>dbo.FbMatch</c> 的半场比分长期是全场比分的副本。根因在采集端
/// <c>FiveHundredMatchSource.ParseRow</c>：拿到结构化比分后无条件把「下一个比分样式的文本」当半场，
/// 而绝大多数场次的页面上只有一个比分文本（就是全场），于是半场 = 全场。
///
/// 全量实测（2026-11-08）：
///   · 84% 的场次「半场 == 全场」；
///   · 半场场均进球 2.58，全场 2.90 —— 半场占 89%（真实约 45%，即 1.3 球）；
///   · 全场 1:0 的比赛里 82.8% 被记成「半场 1:0」（真实约 45%）；
///   · 全场 ≥5 球的比赛里 70.9% 被记成「半场 = 全场」（真实几乎为 0，因为 2:1 全场不可能半场就 2:1 的 70%）。
/// 这个拷贝率不是只在某几个月：小联赛（西协丙/土丙/意丙1A/西协乙/瑞典乙/挪丙/德地区）100%，
/// 主流联赛 78~83%，2026-07~09 达 94~100%，2026-11 号称修复后仍是 84.5%。
///
/// ## 第一版判据是错的（必须记下来）
/// 第一版按「时间窗」判定：认为只有 2026-07-01~10-31 被污染，于是把此前此后当干净窗口，
/// 并据此重算了两张半全场基线。**这是错的**——7 月之前同样是 78~83% 的复制率，
/// 只是没到 100% 而已。教训：**拿「某段时间异常」推「其余时间正常」，必须先在其余时间上做同样的检验。**
///
/// ## 现在的判据：结构判定，不看时间
/// 单场无法区分「真实的半场=全场」（真实足球约 45%）和「拷贝出来的半场=全场」。
/// 所以只采信**必然为真**的那部分：<b>半场比分与全场比分不同</b>。
/// 这类场次的半场值不可能是拷贝（拷贝只会产生相等），且逻辑上必须满足分主客都不超过全场。
///
/// 实测 84,381 条可信样本：
///   · 只有 6 条违反「半场 ≤ 全场」（99.99% 自洽）；
///   · 半场比分分布 0 球 28.6% / 1 球 35.9% / 2 球 22.2% / 3 球 9.4%，场均 1.21 —— 正是真实半场形态；
///   · 全场 1:0 的可信样本里只有 0:0（6,067 条），全场 2:1 的只有 0:0/1:0/0:1/1:1/2:0 —— 全部合法。
///
/// ## 判据分两种，别混用
/// **① 可用性判据（现在用这个，<see cref="IsUsable"/> / <see cref="SqlUsable"/>）**
/// 采集修好、数据重采之后，库里的半场就是真值，判据只剩三条：
/// 非空、分主客都不超过全场。**半场等于全场是合法的**（真实足球约 20% 的场次如此），
/// 不能因为它和全场一样就丢掉——这正是第一版修法犯的错（把 11-07 的同分率压到 0%、样本少三成）。
///
/// **② 抢救判据（只对旧脏数据有效，<see cref="SqlLegacyProvablyGenuine"/>）**
/// 面对已经掺了拷贝的旧数据（备份表 <c>dbo.FbMatch_HalfBackup_20261108</c>），
/// 单场分不清「真实同分」和「拷贝同分」，只能采信**必然为真**的那部分——半场与全场不同。
/// 这类样本不可能是拷贝（拷贝只会产生相等）。
///
/// 旧数据实测 84,381 条可抢救样本：只有 6 条违反「半场 ≤ 全场」（99.99% 自洽）；
/// 半场比分分布 0 球 28.6% / 1 球 35.9% / 2 球 22.2%，场均 1.21 —— 正是真实半场形态。
/// 但**它不能用来定 BQ 九档的绝对概率**：反转档（半场方向≠全场方向）必然落在其中、
/// 计数精确，三个顺风档的主体却被拷在场次里分不出来。
///
/// ⚠ 本类只提供判据，不做自动过滤。SQL 侧显式写 <c>AND {SqlUsable}</c>。
/// </summary>
public static class HalfTimeQuality
{
    /// <summary>
    /// SQL 侧「半场可用」条件（不含前导 AND）。例：<c>WHERE {HalfTimeQuality.SqlUsable}</c>
    /// </summary>
    public const string SqlUsable =
        "(HalfHomeScore IS NOT NULL AND HalfAwayScore IS NOT NULL " +
        "AND HalfHomeScore <= HomeScore AND HalfAwayScore <= AwayScore)";

    /// <summary>
    /// 记忆侧同一判据：半场非空且分主客都不超过全场。
    /// 允许半场 = 全场（真实足球约 20%），**不要**再加「必须不等于全场」——
    /// 那会把真样本一起丢掉，2026-11-08 第一版修法就是这么错的。
    /// </summary>
    public static bool IsUsable(int? halfHome, int? halfAway, int fullHome, int fullAway)
        => halfHome is int hh && halfAway is int ha && hh <= fullHome && ha <= fullAway;

    /// <summary>
    /// 只对**旧脏数据**有效：半场必然为真的那部分样本（半场 ≠ 全场，且不超过全场）。
    /// 用于抢救分析备份表 <c>dbo.FbMatch_HalfBackup_20261108</c>；正常数据不要用它，
    /// 会丢掉约 20% 的真实同分场次。
    /// </summary>
    public const string SqlLegacyProvablyGenuine =
        "(HalfHomeScore IS NOT NULL AND HalfAwayScore IS NOT NULL " +
        "AND (HalfHomeScore <> HomeScore OR HalfAwayScore <> AwayScore) " +
        "AND HalfHomeScore <= HomeScore AND HalfAwayScore <= AwayScore)";

    /// <summary>
    /// 半场比分与全场相同的场次占比。超过此值说明写入路径又在复制全场比分。
    /// 真实值约 20%（500 完场页 2026-11-07 实测 19.3~20.6%），这里留到 65% 才报警，
    /// 给不同联赛结构留余量。
    /// </summary>
    public const double CopyAlarmPct = 65d;
}
